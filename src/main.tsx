import {createRoot} from 'react-dom/client';
import App from './App.tsx';
import './index.css';

createRoot(document.getElementById('root')!).render(<App />);

// Progressive Web App — register the service worker in production
// (Vite dev server would otherwise interfere with the fetch strategy).
if ('serviceWorker' in navigator && import.meta.env.PROD) {
  window.addEventListener('load', () => {
    navigator.serviceWorker
      .register('/sw.js')
      .catch((err) => console.warn('SurgiTrack SW registration skipped:', err));
  });
}
