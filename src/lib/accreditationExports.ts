/* ============================================================
   Official PDF per standard — with digital signature audit page
   ============================================================ */

const STANDARD_META: Record<AccreditationStandard, { title: string; subtitle: string; authority: string; filename: string }> = {
  iscp: {
    title: 'ISCP Surgical Logbook',
    subtitle: 'Intercollegiate Surgical Curriculum Programme — United Kingdom & Ireland',
    authority: 'Prepared in the structure of the ISCP operative logbook',
    filename: 'ISCP_Logbook',
  },
  acgme: {
    title: 'ACGME Case Log',
    subtitle: 'Accreditation Council for Graduate Medical Education — United States',
    authority: 'Prepared in the structure of the ACGME resident case log',
    filename: 'ACGME_CaseLog',
  },
  racs: {
    title: 'Royal College Surgical Logbook',
    subtitle: 'Royal Australasian College of Surgeons / Royal College of Physicians and Surgeons of Canada',
    authority: 'Prepared in the structure of the RACS / Royal College operative logbook',
    filename: 'RoyalCollege_Logbook',
  },
  aeappro: {
    title: 'Operationslogbuch (ÄApprO / WBO)',
    subtitle: 'Approbationsordnung für Ärzte — Weiterbildungsordnung',
    authority: 'Vorbereitet in der Struktur des deutschen Operationslogbuchs nach §5 ÄApprO',
    filename: 'Operationslogbuch_AeApprO',
  },
};

export function exportAccreditationPDF(standard: AccreditationStandard, payload: AccreditationPayload) {
  const meta = STANDARD_META[standard];
  const { trainee, records, supervisors } = payload;
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });

  const sortedRecords = [...records].sort((a, b) =>
    (a.procedureDate || a.trainingDate).localeCompare(b.procedureDate || b.trainingDate)
  );
  const signedRecords = sortedRecords.filter(r => r.signature);
  const totalHours = records.reduce((s, r) => s + (Number(r.netTrainingHours) || 0), 0);

  /* ---- Cover header ---- */
  doc.setFillColor(13, 148, 136);
  doc.rect(0, 0, 210, 34, 'F');
  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(19);
  doc.text(meta.title, 14, 15);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text(meta.subtitle, 14, 23);
  doc.text(`SurgiTrack iLog — International Accreditation Export — ${new Date().toLocaleDateString('en-GB')}`, 14, 29);

  /* ---- Trainee & programme block ---- */
  doc.setTextColor(30, 41, 59);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  doc.text('TRAINEE & PROGRAMME DETAILS', 14, 44);
  autoTable(doc, {
    startY: 47,
    theme: 'grid',
    styles: { fontSize: 8.5, cellPadding: 2.2 },
    headStyles: { fillColor: [240, 253, 250], textColor: [13, 148, 136] },
    head: [['Field', 'Details']],
    body: [
      ['Full Name', trainee.fullName],
      ['Qualification', trainee.medicalQualification],
      ['Specialty / Programme', trainee.specialty],
      ['Current Position', trainee.currentPosition],
      ['Country of Training', trainee.country],
      ['Hospitals / Sites', trainee.hospitals || '—'],
      ['Documented Operations', String(sortedRecords.length)],
      ['Total Supervised Operative Hours', `${totalHours.toFixed(1)} h`],
      ['Supervising Surgeons', String(supervisors.length)],
      ['Digitally Signed Records (SHA-256)', `${signedRecords.length} / ${sortedRecords.length}`],
    ],
    columnStyles: { 0: { cellWidth: 62, fontStyle: 'bold' }, 1: { cellWidth: 'auto' } },
  });

  /* ---- Logbook table ---- */
  let y = (doc as any).lastAutoTable.finalY + 8;
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10.5);
  if (y > 240) { doc.addPage(); y = 18; }
  doc.text(standard === 'aeappro' ? 'OPERATIONSLOGBUCH (EINTRÄGE)' : 'OPERATIVE LOGBOOK ENTRIES', 14, y);

  const tableRows = sortedRecords.map(r => {
    const sup = supervisors.find(s => s.id === r.supervisorId);
    const role = mapRole(r.participationRole);
    const roleText =
      standard === 'iscp' ? role.iscp :
      standard === 'acgme' ? role.acgme :
      standard === 'racs' ? role.racs :
      role.german;
    return [
      r.procedureDate || r.trainingDate,
      r.procedureName || r.activityType,
      roleText,
      sup ? sup.fullName : '—',
      r.hospital,
      r.signature ? 'YES' : '—',
    ];
  });

  const headLabels =
    standard === 'aeappro'
      ? ['Datum', 'Eingriff', 'Eigene Leistung', 'WB-Befugter Arzt', 'Krankenhaus', 'Signiert']
      : ['Date', 'Procedure', 'Role', 'Supervisor', 'Hospital', 'Signed'];

  autoTable(doc, {
    startY: y + 3,
    theme: 'striped',
    styles: { fontSize: 7.6, cellPadding: 1.8 },
    headStyles: { fillColor: [13, 148, 136], textColor: 255 },
    head: [headLabels],
    body: tableRows.length > 0 ? tableRows : [['—', 'No records', '—', '—', '—', '—']],
    columnStyles: {
      0: { cellWidth: 20 },
      1: { cellWidth: 52 },
      2: { cellWidth: 38 },
      3: { cellWidth: 30 },
      4: { cellWidth: 34 },
      5: { cellWidth: 14, halign: 'center' },
    },
  });

  /* ---- Digital signature audit page ---- */
  if (signedRecords.length > 0) {
    doc.addPage();
    doc.setFillColor(67, 56, 202);
    doc.rect(0, 0, 210, 26, 'F');
    doc.setTextColor(255, 255, 255);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(14);
    doc.text('DIGITAL SIGNATURE AUDIT TRAIL', 14, 12);
    doc.setFontSize(8);
    doc.setFont('helvetica', 'normal');
    doc.text('SHA-256 cryptographic attestations — immutable supervisor signatures (SurgiTrack iLog)', 14, 19);

    autoTable(doc, {
      startY: 32,
      theme: 'grid',
      styles: { fontSize: 7.2, cellPadding: 1.8 },
      headStyles: { fillColor: [67, 56, 202], textColor: 255 },
      head: [['Signed At', 'Procedure', 'Supervisor (Signatory)', 'SHA-256 Fingerprint']],
      body: signedRecords.map(r => [
        new Date(r.signature!.signedAt).toLocaleString('en-GB'),
        r.procedureName || r.activityType,
        r.signature!.supervisorName,
        r.signature!.contentHash,
      ]),
      columnStyles: {
        0: { cellWidth: 30 },
        1: { cellWidth: 45 },
        2: { cellWidth: 40 },
        3: { cellWidth: 'auto', font: 'courier', fontSize: 6.2 },
      },
    });

    let ay = (doc as any).lastAutoTable.finalY + 8;
    doc.setTextColor(30, 41, 59);
    doc.setFontSize(7.6);
    doc.setFont('helvetica', 'normal');
    doc.text(
      'Integrity statement: each fingerprint above is a SHA-256 digest of the full clinical content of the record at the',
      14, ay
    );
    doc.text('moment of signing. Any post-signature modification changes the digest and is detectable by re-computation.', 14, ay + 4);
    doc.text('Signed records are locked permanently in SurgiTrack iLog and cannot be edited or deleted.', 14, ay + 8);
  }

  /* ---- Declaration & signature block ---- */
  if ((doc as any).lastAutoTable) {
    let dy = (doc as any).lastAutoTable.finalY + 12;
    if (dy > 235) { doc.addPage(); dy = 30; }

    doc.setDrawColor(13, 148, 136);
    doc.setLineWidth(0.5);
    doc.rect(14, dy, 182, 42);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(9);
    doc.setTextColor(13, 148, 136);
    doc.text(standard === 'aeappro' ? 'ERKLÄRUNG & UNTERSCHRIFTEN' : 'DECLARATION & SIGNATURES', 18, dy + 7);

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.4);
    doc.setTextColor(51, 65, 85);
    const declaration =
      standard === 'aeappro'
        ? 'Ich bestätige, dass alle aufgeführten Eingriffe und Ausbildungsstunden unter meiner Supervision korrekt dokumentiert wurden.'
        : 'I declare that the procedures and training hours listed in this logbook are a true and accurate record of the trainee\'s supervised surgical activity.';
    doc.text(doc.splitTextToSize(declaration, 174), 18, dy + 13);

    doc.setFontSize(7.6);
    doc.text('Trainee: ____________________________', 18, dy + 32);
    doc.text('Date: ______________', 18, dy + 38);
    doc.text('Supervising Consultant: ____________________________', 100, dy + 32);
    doc.text('Date: ______________', 100, dy + 38);
  }

  /* ---- Footer ---- */
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(6.8);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `${meta.authority} — generated by SurgiTrack iLog — page ${i}/${pages}`,
      105,
      291,
      { align: 'center' }
    );
  }

  doc.save(`${meta.filename}_${trainee.fullName.replace(/\s+/g, '_')}.pdf`);
}

export function exportAccreditationCsv(standard: AccreditationStandard, payload: AccreditationPayload) {
  if (standard === 'iscp') return exportISCPCsv(payload);
  if (standard === 'acgme') return exportACGMECsv(payload);
  if (standard === 'racs') return exportRACSCsv(payload);
  return exportAeApproCsv(payload);
}
