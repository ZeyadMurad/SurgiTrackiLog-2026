import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { Supervisor, TrainingRecord, UserProfile, ClinicalCase } from '../types';

/**
 * INTERNATIONAL ACCREDITATION EXPORT ENGINE
 * Maps the SurgiTrack logbook into the submission formats of the four major
 * surgical training authorities:
 *
 *  1. ISCP  — Intercollegiate Surgical Curriculum Programme (UK & Ireland)
 *  2. ACGME — Accreditation Council for Graduate Medical Education (USA)
 *  3. RACS  — Royal Australasian College of Surgeons / Royal College logbooks
 *             (used by RACS and the Royal Colleges of Surgeons of Canada)
 *  4. ÄApprO — German Approbationsordnung für Ärzte / WBO operative logbook
 *
 * Every export embeds the digital signature audit trail (SHA-256 fingerprints)
 * so receiving authorities can verify record integrity.
 */

export type AccreditationStandard = 'iscp' | 'acgme' | 'racs' | 'aeappro';

export interface AccreditationPayload {
  trainee: UserProfile;
  records: TrainingRecord[];
  cases: ClinicalCase[];
  supervisors: Supervisor[];
}

/* ============================================================
   Role mapping — the single hardest part of any logbook mapping
   ============================================================ */

type RoleMap = {
  iscp: string;   // UK ISCP participation
  acgme: string;  // US ACGME case-log role
  racs: string;   // Australasian / Royal College role
  german: string; // German WBO legal term
};

function mapRole(participationRole: string): RoleMap {
  const r = (participationRole || '').toLowerCase();
  if (r.includes('performed under supervision') && r.includes('specific steps')) {
    return {
      iscp: 'Performed steps under direct supervision',
      acgme: 'Surgeon Junior (supervised steps)',
      racs: 'Performed part under supervision (P2)',
      german: 'Unter Aufsicht (teilweise)',
    };
  }
  if (r.includes('performed under supervision')) {
    return {
      iscp: 'Performed under supervision',
      acgme: 'Surgeon Junior',
      racs: 'Performed under supervision (P2)',
      german: 'Unter Aufsicht',
    };
  }
  if (r.includes('first assistant')) {
    return {
      iscp: 'First assistant',
      acgme: 'First Assistant',
      racs: 'First assistant (A1)',
      german: 'Assistiert (1. Assistenz)',
    };
  }
  if (r.includes('second assistant')) {
    return {
      iscp: 'Second assistant',
      acgme: 'Second Assistant',
      racs: 'Assistant (A2)',
      german: 'Assistiert (2. Assistenz)',
    };
  }
  if (r.includes('assisted')) {
    return {
      iscp: 'Assistant',
      acgme: 'Assistant',
      racs: 'Assistant (A2)',
      german: 'Assistiert',
    };
  }
  if (r.includes('observer')) {
    return {
      iscp: 'Observer',
      acgme: 'Observer',
      racs: 'Observer (O)',
      german: 'Beobachtung (Zuschauer)',
    };
  }
  return {
    iscp: participationRole,
    acgme: participationRole,
    racs: participationRole,
    german: participationRole,
  };
}

const caseRef = (payload: AccreditationPayload, record: TrainingRecord): ClinicalCase | undefined =>
  payload.cases.find(c => c.caseReference === record.clinicalCaseRef || c.id === record.clinicalCaseRef);

const supervisorOf = (payload: AccreditationPayload, record: TrainingRecord): Supervisor | undefined =>
  payload.supervisors.find(s => s.id === record.supervisorId);

/* ============================================================
   CSV download helper (BOM + Excel-safe quoting)
   ============================================================ */

function downloadCSV(filename: string, rows: (string | number)[][]) {
  const csv = rows
    .map(r =>
      r
        .map(cell => {
          const s = String(cell ?? '');
          return /[",\n;]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
        })
        .join(',')
    )
    .join('\r\n');
  const blob = new Blob(['\ufeff' + csv], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  setTimeout(() => URL.revokeObjectURL(url), 1500);
}

/* ============================================================
   1. ISCP — UK Intercollegiate Surgical Curriculum Programme
   ============================================================ */

export function exportISCPCsv(payload: AccreditationPayload) {
  const { trainee } = payload;
  const rows: (string | number)[][] = [
    ['ISCP SURGICAL LOGBOOK EXPORT (Intercollegiate Surgical Curriculum Programme — UK & Ireland)'],
    ['Generated by SurgiTrack iLog on', new Date().toISOString().substring(0, 10)],
    ['Trainee', trainee.fullName, 'GMC-level ID', trainee.email],
    ['Specialty', trainee.specialty, 'Placement / Hospital', trainee.hospitals || '—'],
    [],
    ['Date', 'Procedure', 'Operative Approach', 'Role in Procedure', 'Supervision Level', 'Supervising Consultant', 'Hospital', 'Case Ref', 'Duration (h)', 'Signed (SHA-256)', 'Notes / Learning Points'],
  ];

  payload.records.forEach(r => {
    const c = caseRef(payload, r);
    const sup = supervisorOf(payload, r);
    rows.push([
      r.procedureDate || r.trainingDate,
      r.procedureName || r.activityType,
      c?.surgicalProcedure?.surgicalApproach || '—',
      mapRole(r.participationRole).iscp,
      r.supervisionLevel,
      sup ? `${sup.academicDegree || ''} ${sup.fullName}`.trim() : r.supervisorId,
      r.hospital,
      r.clinicalCaseRef || '—',
      r.netTrainingHours,
      r.signature ? r.signature.contentHash.substring(0, 16) + '…' : 'unsigned',
      r.learningPoints || r.descriptionOfParticipation || '',
    ]);
  });

  downloadCSV(`ISCP_Logbook_${trainee.fullName.replace(/\s+/g, '_')}.csv`, rows);
}

